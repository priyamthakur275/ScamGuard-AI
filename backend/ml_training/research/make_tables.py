"""Turns results.json into results.md (the tables used in the paper).

    python -m ml_training.research.make_tables
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def ci(m: dict, key: str) -> str:
    c = m.get(f"{key}_ci")
    return f" ({pct(c[0])}-{pct(c[1])})" if c else ""


def row(name: str, m: dict) -> str:
    return (f"| {name} | {m['n']} | {pct(m['accuracy'])} | {pct(m['precision'])} | {pct(m['recall'])} | {pct(m['f1'])}{ci(m, 'f1')} | "
            f"{pct(m['fpr'])}{ci(m, 'fpr')} | {m.get('roc_auc', float('nan')):.3f} |")


HEAD = "| System | n | Accuracy | Precision | Recall | F1 (95% CI) | False-alarm rate (95% CI) | ROC-AUC |\n|---|---|---|---|---|---|---|---|"


def main() -> int:
    R = json.load(open(os.path.join(HERE, "results.json")))
    out = ["# ScamGuard-IN-2026 results", "", "Generated by `make_tables.py` from `results.json` (`run_experiments.py`). Percentages; 95% CIs by 1,000 bootstrap resamples.", ""]
    d = R["dataset"]
    out += ["## Dataset", "", f"{d['rows']} rows. By split and label: " + ", ".join(f"{k.replace('|', ' ')} {v}" for k, v in d["by_split_label"].items()) + ".", ""]

    out += ["## Deployed system (classifier + intent rules)", "", HEAD]
    for k, name in (("real_test", "real test"), ("challenge", "dev challenge set"), ("test_2026", "2025-26 set")):
        out.append(row(f"deployed system - {name}", R["E5_fusion"][k]["hand_fusion"]))
    out.append("")

    out += ["## E1. Near-duplicate leakage (same data, same model)", "", HEAD]
    e = R["E1_leakage"]
    out += [row("random row split", e["random_row_split"]), row("campaign-aware split", e["campaign_split"]), "",
            f"With a random split, {e['test_rows_with_near_duplicate_in_train_random']} test rows had a near-duplicate of the same campaign in training.", ""]

    if R.get("E2_models"):
        out += ["## E2. Models and features (real test)", "", "| Model | Features | F1 | False-alarm rate | Challenge F1 |", "|---|---|---|---|---|"]
        for key, v in R["E2_models"].items():
            m, f = key.split("|")
            out.append(f"| {m} | {f} | {pct(v['real_test']['f1'])} | {pct(v['real_test']['fpr'])} | {pct(v['challenge']['f1'])} |")
        out.append("")

    out += ["## E3. Training data (classifier alone)", "", HEAD]
    for k, v in R["E3_training_data"].items():
        out.append(row(f"{k} - real test", v["real_test"]))
        out.append(row(f"{k} - dev challenge", v["challenge"]))
    out.append("")

    out += ["## E4. Label audit (classifier alone, real test)", "", HEAD,
            row("IMC'25 reports taken as scam", R["E4_label_audit"]["reported_equals_scam"]["real_test"]),
            row("audited labels", R["E4_label_audit"]["audited"]["real_test"]), "",
            f"McNemar (audited vs reported): {R['E4_label_audit']['mcnemar_real_test']}", ""]

    out += ["## E5. Evidence fusion", "", HEAD]
    for k in ("real_test", "challenge", "test_2026"):
        if k in R["E5_fusion"]:
            for n in ("classifier", "hand_fusion", "learned_fusion"):
                out.append(row(f"{n} - {k}", R["E5_fusion"][k][n]))
    out += ["", f"McNemar learned vs hand fusion on real test: {R['E5_fusion']['real_test']['mcnemar_learned_vs_hand']}", ""]
    w = R["E5_fusion"]["learned_weights"]
    out += ["Largest learned fusion weights: " + ", ".join(f"{k} {v:+.2f}" for k, v in list(w.items())[:12]), ""]
    with open(os.path.join(HERE, "results.md"), "w") as fh:
        fh.write("\n".join(out) + "\n")
    print("\n".join(out[:20]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
